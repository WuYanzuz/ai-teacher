"""Migrate the SQLite database into Oracle (schema AIWECHAT).

Source is opened READ-ONLY with the stdlib sqlite3 (no peewee needed); target
is the SQLAlchemy/oracledb engine from config.yaml (database.dialect=oracle).

What it does
  1. inserts rows in FK order, INCLUDING explicit ids (Oracle IDENTITY is
     GENERATED BY DEFAULT, so explicit ids are allowed);
  2. normalizes "" -> None (Oracle treats '' as NULL), parses timestamps;
  3. backfills homework.child_name from the child table;
  4. bumps every IDENTITY sequence past max(id) so new inserts won't collide;
  5. prints row-count reconciliation.

Idempotent: a non-empty target table is skipped. Use --truncate to wipe the
target schema's tables first (rows only; tables must already exist — start the
backend once or run check_oracle.py --create-tables).

Usage:
    python scripts/migrate_sqlite_to_oracle.py
    python scripts/migrate_sqlite_to_oracle.py --source data/ai_teacher.db --truncate
"""

from __future__ import annotations

import argparse
import sqlite3
import sys
from datetime import datetime
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT_ROOT))

from sqlalchemy import text  # noqa: E402

# (target table, source table candidates, columns in target order)
TABLES: list[tuple[str, list[str], list[str]]] = [
    ("app_user", ["app_user", "user"], ["id", "openid", "role", "name", "avatar_url", "created_at", "last_login"]),
    ("classroom", ["classroom"], ["id", "name", "code", "teacher_id", "created_at"]),
    ("membership", ["membership"], ["id", "user_id", "classroom_id", "child_name", "created_at"]),
    ("auth_token", ["auth_token"], ["id", "token", "user_id", "created_at", "expires_at"]),
    ("child", ["child"], ["id", "name", "parent_wxid", "group_nick_pattern", "first_seen", "last_seen", "notes"]),
    ("homework", ["homework"], [
        "id", "child_id", "group_roomid", "msg_id", "media_type", "media_path",
        "raw_transcript", "is_homework", "feedback", "teacher_review", "created_at",
        "submit_user_id", "classroom_id",
    ]),
    ("growthmetric", ["growthmetric"], ["id", "child_id", "homework_id", "dimension", "score", "note", "created_at"]),
]

# Children first for delete ordering; include new feature tables.
ALL_TARGET_TABLES = [
    "growthmetric", "homework", "child", "auth_token", "membership", "classroom", "app_user",
    "growth_checkin_item", "growth_checkin",
    "growth_template_option", "growth_template",
    "child_report", "report_batch",
]

TS_COLS = {"created_at", "last_login", "expires_at", "first_seen", "last_seen"}
INT_COLS = {"id", "teacher_id", "user_id", "classroom_id", "child_id", "homework_id",
            "msg_id", "is_homework", "submit_user_id", "score"}


def parse_ts(v):
    if v is None or v == "":
        return None
    if isinstance(v, datetime):
        return v
    s = str(v).strip().replace("T", " ").replace("Z", "")
    # Legacy rows may store a Unix timestamp (float seconds), e.g. "1787298154.166".
    if s.replace(".", "", 1).isdigit() and len(s.split(".")[0]) >= 9:
        try:
            return datetime.fromtimestamp(float(s))
        except (ValueError, OverflowError, OSError):
            pass
    for fmt in ("%Y-%m-%d %H:%M:%S.%f", "%Y-%m-%d %H:%M:%S", "%Y-%m-%d"):
        try:
            return datetime.strptime(s, fmt)
        except ValueError:
            continue
    try:
        return datetime.fromisoformat(str(v))
    except ValueError:
        print(f"  WARN: unparsable timestamp {v!r}, writing NULL")
        return None


def clean(col, v):
    if col in TS_COLS:
        return parse_ts(v)
    if v == "":
        return None  # Oracle '' IS NULL
    if col in INT_COLS and v is not None:
        return int(v)
    return v


def open_source(path: Path) -> sqlite3.Connection:
    uri = path.resolve().as_uri() + "?mode=ro"
    con = sqlite3.connect(uri, uri=True)
    con.row_factory = sqlite3.Row
    return con


def source_table(con: sqlite3.Connection, candidates: list[str]) -> str | None:
    names = {
        r[0]
        for r in con.execute("SELECT name FROM sqlite_master WHERE type='table'")
    }
    for name in candidates:
        if name in names:
            return name
    return None


def bump_identity(conn, table: str) -> None:
    """Advance the table's IDENTITY sequence past max(id)."""
    max_id = conn.execute(text(f'SELECT MAX(id) FROM "{table}"')).scalar()
    if max_id is None:
        return
    seq = conn.execute(
        text("SELECT sequence_name FROM user_tab_identity_cols WHERE table_name = :t"),
        {"t": table.upper()},
    ).scalar()
    if not seq:
        print(f"  WARN: no identity sequence found for {table}")
        return
    cur = conn.execute(text(f'SELECT "{seq}".NEXTVAL FROM dual')).scalar()
    if cur >= max_id:
        return
    gap = max_id - cur + 1
    conn.execute(text(f'ALTER SEQUENCE "{seq}" INCREMENT BY {int(gap)}'))
    conn.execute(text(f'SELECT "{seq}".NEXTVAL FROM dual')).scalar()
    conn.execute(text('ALTER SEQUENCE "' + seq + '" INCREMENT BY 1'))
    conn.commit()


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--source", default=str(PROJECT_ROOT / "data" / "ai_teacher.db"))
    ap.add_argument("--truncate", action="store_true",
                    help="delete all rows from target tables first")
    args = ap.parse_args()

    src_path = Path(args.source)
    if not src_path.exists():
        print(f"ERROR: source DB not found: {src_path}", file=sys.stderr)
        return 1

    from dotenv import load_dotenv
    load_dotenv(PROJECT_ROOT / ".env", override=False)

    # Make sure we talk to Oracle, regardless of the dev config dialect.
    import yaml
    db_cfg = yaml.safe_load((PROJECT_ROOT / "config.yaml").read_text(encoding="utf-8")).get("database", {})
    if db_cfg.get("dialect", "sqlite").lower() != "oracle":
        print("ERROR: config.yaml database.dialect must be 'oracle' for migration", file=sys.stderr)
        return 1

    import ai_teacher.storage.models  # noqa: F401
    import backend.models  # noqa: F401
    from ai_teacher.storage.database import get_engine
    engine = get_engine()
    if engine.dialect.name != "oracle":
        print("ERROR: engine is not oracle (check ORACLE_PASSWORD / service_name)", file=sys.stderr)
        return 1

    src = open_source(src_path)
    print(f"source (read-only): {src_path}")

    with engine.begin() as conn:
        who = conn.execute(text("SELECT SYS_CONTEXT('USERENV','CURRENT_USER') FROM dual")).scalar()
        print(f"target: {who}\n")

        if args.truncate:
            print("truncating target tables ...")
            for t in ALL_TARGET_TABLES:
                conn.execute(text(f'DELETE FROM "{t}"'))
            conn.commit()

        summary = []
        for target, candidates, cols in TABLES:
            src_name = source_table(src, candidates)
            if src_name is None:
                print(f"- {target}: source table missing, skip")
                summary.append((target, 0, 0))
                continue
            n_src = src.execute(f'SELECT COUNT(*) FROM "{src_name}"').fetchone()[0]
            n_dst = conn.execute(text(f'SELECT COUNT(*) FROM "{target}"')).scalar()
            if n_dst:
                print(f"- {target}: target has {n_dst} rows, skip (use --truncate to redo)")
                summary.append((target, n_src, n_dst))
                continue
            rows = src.execute(f'SELECT {", ".join(cols)} FROM "{src_name}"').fetchall()
            batch = [
                {c: clean(c, row[c]) for c in cols}
                for row in rows
            ]
            if batch:
                conn.execute(
                    text(
                        f'INSERT INTO "{target}" ({", ".join(cols)}) '
                        f'VALUES ({", ".join(":" + c for c in cols)})'
                    ),
                    batch,
                )
            conn.commit()
            print(f"- {target}: {len(batch)} rows")
            summary.append((target, n_src, len(batch)))
            bump_identity(conn, target)

        # Backfill denormalized child_name.
        result = conn.execute(text("""
            UPDATE homework h
               SET child_name = (SELECT name FROM child c WHERE c.id = h.child_id)
             WHERE h.child_name IS NULL
        """))
        conn.commit()
        print(f"\nhomework.child_name backfilled: {result.rowcount} rows")

    print("\n=== reconciliation (source -> inserted) ===")
    bad = 0
    for table, n_src, n_dst in summary:
        flag = "OK" if n_src == n_dst or n_dst > 0 else "MISMATCH"
        if n_src and n_dst == 0:
            flag = "MISMATCH"; bad += 1
        print(f"  {table:16s} {n_src:5d} -> {n_dst:5d}  {flag}")
    print("\nDone. Next: restart the backend (seeds check-in templates), then run e2e.")
    return 1 if bad else 0


if __name__ == "__main__":
    raise SystemExit(main())
