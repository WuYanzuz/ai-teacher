"""Oracle connectivity check + DDL export for the AIWECHAT schema.

Usage (run from project root):

    # 1. After scripts/sql/01_oracle_schema.sql created the AIWECHAT user,
    #    put its password in .env (ORACLE_PASSWORD=...) and set
    #    config.yaml -> database.dialect: oracle, then:
    python scripts/check_oracle.py

    # 2. Render the DDL for DBA review (no connection needed):
    python scripts/check_oracle.py --dump-ddl

    # 3. Create tables in the connected schema (normally backend startup does
    #    this automatically; use this for an explicit first deploy):
    python scripts/check_oracle.py --create-tables
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT_ROOT))

from sqlalchemy import text  # noqa: E402
from sqlalchemy.dialects import oracle  # noqa: E402
from sqlalchemy.schema import CreateTable  # noqa: E402


def _load_models():
    """Import both model modules so every table is registered."""
    import ai_teacher.storage.models  # noqa: F401
    import backend.models  # noqa: F401
    from ai_teacher.storage.database import Base
    return Base


def cmd_dump_ddl(out_path: Path) -> int:
    base = _load_models()
    # Identity columns render on Oracle 12+; pin the dialect to 19c.
    dialect = oracle.dialect()
    dialect.server_version_info = (19, 0, 0, 0, 0)
    lines = [
        "-- Generated by scripts/check_oracle.py --dump-ddl",
        "-- Target: Oracle 19c+, schema AIWECHAT. Review only; backend startup",
        "-- runs the same create_all() automatically (checkfirst).",
        "",
    ]
    for table in base.metadata.sorted_tables:
        ddl = str(CreateTable(table).compile(dialect=dialect)).strip()
        lines.append(ddl.rstrip(";") + ";")
        lines.append("")
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {len(base.metadata.sorted_tables)} tables -> {out_path}")
    return 0


def _connect():
    # Force the oracle branch regardless of the local config dialect, so the
    # check is meaningful even while dev config points at sqlite.
    import os
    import yaml
    import oracledb
    from dotenv import load_dotenv
    load_dotenv(PROJECT_ROOT / ".env", override=False)
    cfg = yaml.safe_load((PROJECT_ROOT / "config.yaml").read_text(encoding="utf-8"))
    db_cfg = cfg.get("database", {})
    user = db_cfg.get("user", "AIWECHAT")
    password = os.getenv("ORACLE_PASSWORD", "")
    dsn = os.getenv("ORACLE_DSN", "").strip()
    if not dsn:
        dsn = f"{db_cfg.get('host', '127.0.0.1')}:{db_cfg.get('port', 1521)}/{db_cfg.get('service_name', 'XEPDB1')}"
    if not password:
        print("ERROR: ORACLE_PASSWORD not set in environment/.env", file=sys.stderr)
        return None
    try:
        conn = oracledb.connect(user=user, password=password, dsn=dsn)
    except Exception as e:
        print(f"ERROR: connect failed: {e}", file=sys.stderr)
        return None
    print(f"connected: {user}@{dsn}")
    return conn


def cmd_check(create_tables: bool) -> int:
    conn = _connect()
    if conn is None:
        return 1
    ok = True
    try:
        with conn.cursor() as cur:
            v = cur.execute("SELECT version FROM product_component_version WHERE UPPER(product) LIKE 'ORACLE DATABASE%'").fetchone()
            print("DB version:", v[0] if v else "?")
            who = cur.execute("SELECT SYS_CONTEXT('USERENV','CURRENT_USER'), SYS_CONTEXT('USERENV','CON_NAME') FROM dual").fetchone()
            print("user / container:", who[0], "/", who[1])
            priv = {r[0] for r in cur.execute("SELECT privilege FROM session_privs")}
            for need in ("CREATE SESSION", "CREATE TABLE"):
                print(f"priv {need}:", "OK" if need in priv else "MISSING")
                ok &= need in priv
            quota = cur.execute(
                "SELECT tablespace_name, max_bytes FROM user_ts_quotas"
            ).fetchall()
            print("tablespace quotas:", quota or "(none — QUOTA needed!)")
    finally:
        conn.close()

    if create_tables and ok:
        from ai_teacher.storage.database import get_engine
        import ai_teacher.storage.models  # noqa: F401
        import backend.models  # noqa: F401
        from ai_teacher.storage.database import Base
        engine = get_engine()
        if engine.dialect.name != "oracle":
            print("ERROR: config database.dialect is not oracle", file=sys.stderr)
            return 1
        Base.metadata.create_all(engine)
        with engine.connect() as c:
            n = c.execute(text("SELECT count(*) FROM user_tables")).scalar()
        print(f"create_all done; user_tables now: {n}")
    return 0 if ok else 1


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dump-ddl", action="store_true", help="render Oracle DDL and exit")
    ap.add_argument("--create-tables", action="store_true", help="create tables in the connected schema")
    ap.add_argument("--out", default=str(PROJECT_ROOT / "scripts" / "sql" / "02_create_tables.sql"))
    args = ap.parse_args()
    if args.dump_ddl:
        return cmd_dump_ddl(Path(args.out))
    return cmd_check(args.create_tables)


if __name__ == "__main__":
    raise SystemExit(main())
